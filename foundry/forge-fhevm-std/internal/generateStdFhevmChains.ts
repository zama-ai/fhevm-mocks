// Generates pkg/src/StdFhevmChains.sol from internal/StdFhevmChains.sol.template.
//
// The table of deployed chains has to be compiled in: a project that installs this package has no
// fhevm-chains.config.json to read at run time. So the template carries everything written by hand (the
// library's logic, the local `anvil` entry, the default group of each alias), and this generator fills its one
// placeholder, {{FHEVM_NETWORK_CHAINS}}, with one entry per host chain of each network group of the
// workspace's fhevm-chains.config.json (NR-91: every copy of a deployed address follows that file).
//
// The config does not hold two things the table gives: the public alias a test types, and a default RPC URL.
// Both are forge-std's: internal/fhevm-chain-aliases.json, keyed by group and config host key, is GENERATED by
// internal/chain-aliases/ChainAliases.s.sol, which asks forge-std's StdChains for each chain ID (`npm run
// generate:chain-aliases`, which generate:pre runs first). A config host without an entry there, or an entry for
// a host the config no longer lists, means that file is older than the config: regenerate it.
//
// Entries follow the config's order of groups and hosts. Run it after `fhevm-npm sync fhevm-chains`, before
// `forge build`: the table is a compile input.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

////////////////////////////////////////////////////////////////////////////////

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const WORKSPACE_ROOT = join(ROOT, '..', '..');

export const CONFIG_PATH = join(WORKSPACE_ROOT, 'fhevm-chains.config.json');
export const ALIASES_PATH = join(ROOT, 'internal', 'fhevm-chain-aliases.json');
export const TEMPLATE_PATH = join(ROOT, 'internal', 'StdFhevmChains.sol.template');
export const OUTPUT_PATH = join(ROOT, 'pkg', 'src', 'StdFhevmChains.sol');

const PLACEHOLDER = '        {{FHEVM_NETWORK_CHAINS}}\n';

/** The host contracts an entry names, required unless listed in OPTIONAL_HOST_CONTRACTS. */
const HOST_CONTRACTS = ['acl', 'fhevmExecutor', 'inputVerifier', 'kmsVerifier', 'protocolConfig', 'kmsGeneration'];
/** A host without one of these gets `address(0)`: only some hosts carry a host-level KMSGeneration. */
const OPTIONAL_HOST_CONTRACTS = new Set(['kmsGeneration']);
/** The gateway contracts an entry names, the same for every host of a group. */
const GATEWAY_CONTRACTS = ['decryption', 'inputVerification'];

const ADDRESS = /^0x[0-9a-fA-F]{40}$/;

////////////////////////////////////////////////////////////////////////////////

type Contracts = Readonly<Record<string, { readonly address?: unknown } | undefined>>;
type Host = { readonly id?: unknown; readonly contracts?: Contracts };
type Network = {
  readonly relayerUrl?: unknown;
  readonly gateway?: { readonly contracts?: Contracts };
  readonly hosts?: Readonly<Record<string, Host>>;
};
export type ChainsConfig = { readonly networks?: Readonly<Record<string, Network>> };

type AliasEntry = { readonly alias?: unknown; readonly rpcUrl?: unknown };
export type ChainAliases = Readonly<Record<string, unknown>>;

////////////////////////////////////////////////////////////////////////////////

function fail(message: string): never {
  throw new Error(`generateStdFhevmChains: ${message}`);
}

function address(value: unknown, what: string): string {
  if (typeof value !== 'string' || !ADDRESS.test(value)) fail(`${what}: expected a 0x-prefixed 20-byte address`);
  return value;
}

function text(value: unknown, what: string): string {
  // Written between quotes in Solidity source: printable ASCII only, and no quote or backslash, so the output is a
  // literal solc accepts as it is.
  if (typeof value !== 'string' || !/^[\x20-\x7e]+$/.test(value) || /["\\]/.test(value)) {
    fail(`${what}: expected a non-empty printable ASCII string without a quote or a backslash`);
  }
  return value;
}

function aliasesOf(aliases: ChainAliases, group: string): Readonly<Record<string, AliasEntry>> {
  const entry = aliases[group];
  if (entry === undefined) return {};
  if (typeof entry !== 'object' || entry === null) fail(`fhevm-chain-aliases.json: "${group}" is not an object`);
  return entry as Readonly<Record<string, AliasEntry>>;
}

/** One `setFhevmChainWithDefaultRpcUrl(...)` call, indented as the template's local entry is. */
function renderEntry(group: string, network: Network, hostKey: string, host: Host, alias: AliasEntry): string {
  const where = `${group}.hosts.${hostKey}`;
  const chainId = host.id;
  if (typeof chainId !== 'number' || !Number.isInteger(chainId) || chainId <= 0)
    fail(`${where}.id: expected a chain ID`);

  const fields: Array<[string, string]> = [
    ['fhevmGroup', `FHEVM_${group.toUpperCase()}_GROUP`],
    ['chainId', String(chainId)],
    ['rpcUrl', `"${text(alias.rpcUrl, `fhevm-chain-aliases.json ${group}.${hostKey}.rpcUrl`)}"`],
    ['relayerUrl', `"${text(network.relayerUrl, `${group}.relayerUrl`)}"`],
  ];
  for (const name of HOST_CONTRACTS) {
    const value = host.contracts?.[name]?.address;
    fields.push([
      name,
      value === undefined && OPTIONAL_HOST_CONTRACTS.has(name)
        ? 'address(0)'
        : address(value, `${where}.contracts.${name}`),
    ]);
  }
  for (const name of GATEWAY_CONTRACTS) {
    fields.push([name, address(network.gateway?.contracts?.[name]?.address, `${group}.gateway.contracts.${name}`)]);
  }

  return [
    '        setFhevmChainWithDefaultRpcUrl(',
    `            "${text(alias.alias, `fhevm-chain-aliases.json ${group}.${hostKey}.alias`)}",`,
    '            FhevmChainData({',
    fields.map(([name, value]) => `                ${name}: ${value}`).join(',\n'),
    '            })',
    '        );',
  ].join('\n');
}

/** The text that replaces the placeholder: a `// <group>` comment, then its entries, for each group in order. */
export function renderNetworkChains(config: ChainsConfig, aliases: ChainAliases): string {
  const networks = config.networks ?? fail('fhevm-chains.config.json has no "networks"');
  const blocks: string[] = [];
  for (const [group, network] of Object.entries(networks)) {
    const hosts = Object.entries(network.hosts ?? {});
    const groupAliases = aliasesOf(aliases, group);
    for (const hostKey of Object.keys(groupAliases)) {
      if (!hosts.some(([key]) => key === hostKey)) {
        fail(
          `fhevm-chain-aliases.json names ${group}.${hostKey}, which fhevm-chains.config.json does not list: ` +
            'run `npm run generate:chain-aliases`',
        );
      }
    }
    if (hosts.length === 0) continue;
    const entries = hosts.map(([hostKey, host]) => {
      const alias =
        groupAliases[hostKey] ??
        fail(
          `fhevm-chains.config.json lists ${group}.hosts.${hostKey} (chain ${String(host.id)}), and ` +
            `internal/fhevm-chain-aliases.json has no entry for it: run \`npm run generate:chain-aliases\``,
        );
      return renderEntry(group, network, hostKey, host, alias);
    });
    blocks.push([`        // ${group}`, ...entries].join('\n') + '\n');
  }
  for (const group of Object.keys(aliases)) {
    if (!group.startsWith('$') && !(group in networks)) {
      fail(`fhevm-chain-aliases.json names the group "${group}", which fhevm-chains.config.json does not have`);
    }
  }
  return blocks.join('\n');
}

/** The whole generated file. The template must hold the placeholder exactly once. */
export function renderStdFhevmChains(template: string, config: ChainsConfig, aliases: ChainAliases): string {
  const parts = template.split(PLACEHOLDER);
  if (parts.length !== 2) fail(`the template must hold the line "${PLACEHOLDER.trim()}" exactly once`);
  for (const group of Object.keys(config.networks ?? {})) {
    const constant = `FHEVM_${group.toUpperCase()}_GROUP`;
    if (!template.includes(`string constant ${constant} = "${group}";`)) {
      fail(`the template declares no \`string constant ${constant} = "${group}";\` for the config's group`);
    }
  }
  return `${parts[0] ?? ''}${renderNetworkChains(config, aliases)}${parts[1] ?? ''}`;
}

////////////////////////////////////////////////////////////////////////////////

/** Renders from the files on disk. With `check`, writes nothing and says whether the committed file is current. */
export function generateStdFhevmChains(options: { readonly check: boolean }): 'written' | 'identical' | 'different' {
  const rendered = renderStdFhevmChains(
    readFileSync(TEMPLATE_PATH, 'utf8'),
    JSON.parse(readFileSync(CONFIG_PATH, 'utf8')) as ChainsConfig,
    JSON.parse(readFileSync(ALIASES_PATH, 'utf8')) as ChainAliases,
  );
  let current: string | undefined;
  try {
    current = readFileSync(OUTPUT_PATH, 'utf8');
  } catch {
    current = undefined;
  }
  if (options.check) return current === rendered ? 'identical' : 'different';
  if (current === rendered) return 'identical';
  writeFileSync(OUTPUT_PATH, rendered, 'utf8');
  return 'written';
}
