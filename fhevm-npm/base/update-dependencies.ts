// `update dependencies`: move every `^`/`~` floor to the version npm would install today if nothing younger than a
// minimum age existed, then let npm lock exactly that. The floor and the lock then name the same version (the
// package.json says what is installed), and nothing locked is younger than the age safe-chain enforces.
//
// What moves, and what never does:
//   - private packages (dev, shared helpers, internal consumers, consumer fixtures, the roots, fhevm-npm itself):
//     every `dependencies`, `devDependencies` and `optionalDependencies` floor;
//   - published packages: `devDependencies` only. Their `dependencies` and `peerDependencies` are the ranges their
//     users install against, and raising one is a release decision, never a refresh;
//   - never: `peerDependencies` anywhere, the npm-manifest.json pins (`sync pinned` owns them), exact versions,
//     `file:`, `npm:` and any other spec, and a package no lockfile covers.
// Every declaration of a name under the same spec gets the same target (one registry answer), so the specs that
// rule 4.2.1 requires to match the root's still match after the update.

import { existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

import type { NpmManifest } from '../manifest.ts';
import { type DependencyField, type LoadedPackage, type PackageJson, dependencyFields } from './npm.ts';
import { type FloorRange, type Packument, parseFloorRange, pickBefore } from './registry-age.ts';
import { compareVersions, parseVersion } from './semver.ts';
import type { PinnedEdit } from './sync-pinned.ts';

/** One package.json the update may edit, with the lockfile that locks it. */
export type UpdateTarget = {
  readonly key: string;
  readonly directory: string;
  readonly packageJson: PackageJson;
  readonly published: boolean;
  /** The directory whose package-lock.json locks this package: an installation root, or the package itself. */
  readonly lockRoot: string;
  /** A consumer fixture with its own lockfile, regenerated by fhevm-npm rather than by `npm install`. */
  readonly isolatedConsumer: boolean;
};

export type FloorEdit = PinnedEdit & { readonly lockRoot: string; readonly isolatedConsumer: boolean };

/** A floor the update leaves alone although it is in scope, and why. */
export type HeldFloor = {
  readonly packageKey: string;
  readonly field: DependencyField;
  readonly name: string;
  readonly spec: string;
  readonly reason: string;
};

export type UpdatePlan = { readonly edits: readonly FloorEdit[]; readonly held: readonly HeldFloor[] };

/**
 * Every manifest package a lockfile covers, plus fhevm-npm's own root (an installation root the manifest does not
 * inventory). A member is locked by its installation root; a non-member with a package-lock.json locks itself.
 */
export function updateTargets(
  packages: readonly LoadedPackage[],
  toolPackage?: { readonly directory: string; readonly packageJson: PackageJson },
): readonly UpdateTarget[] {
  const targets = packages.flatMap((pkg): UpdateTarget[] => {
    const own = existsSync(join(pkg.directory, 'package-lock.json'));
    const lockRootKey =
      pkg.inventory.kind === 'workspace-root'
        ? pkg.key
        : pkg.inventory.member
          ? (pkg.inventory.memberOf ?? '.')
          : own
            ? pkg.key
            : undefined;
    if (lockRootKey === undefined) return [];
    const lockRoot = packages.find((candidate) => candidate.key === lockRootKey)?.directory ?? pkg.directory;
    return [
      {
        key: pkg.key,
        directory: pkg.directory,
        packageJson: pkg.packageJson,
        published: pkg.inventory.kind === 'published',
        lockRoot,
        isolatedConsumer: pkg.inventory.kind !== 'workspace-root' && !pkg.inventory.member,
      },
    ];
  });
  if (toolPackage === undefined) return targets;
  return [
    ...targets,
    {
      key: './fhevm-npm',
      ...toolPackage,
      published: false,
      lockRoot: toolPackage.directory,
      isolatedConsumer: false,
    },
  ];
}

/** The fields the update may move in one package; see the header. */
export function updatableFields(target: UpdateTarget): readonly DependencyField[] {
  if (target.published) return ['devDependencies'];
  return dependencyFields.filter((field) => field !== 'peerDependencies');
}

/** Every in-scope floor, by name: what the registry must be asked. */
export function updatableNames(manifest: NpmManifest, targets: readonly UpdateTarget[]): readonly string[] {
  const pinned = new Set(Object.keys(manifest.dependencies?.pinned ?? {}));
  const names = new Set<string>();
  for (const target of targets) {
    for (const field of updatableFields(target)) {
      for (const [name, spec] of Object.entries(target.packageJson[field] ?? {})) {
        if (!pinned.has(name) && parseFloorRange(spec) !== undefined) names.add(name);
      }
    }
  }
  return [...names].sort();
}

export function planFloorUpdates(
  manifest: NpmManifest,
  targets: readonly UpdateTarget[],
  packuments: ReadonlyMap<string, Packument | undefined>,
  cutoff: Date,
): UpdatePlan {
  const pinned = new Set(Object.keys(manifest.dependencies?.pinned ?? {}));
  const edits: FloorEdit[] = [];
  const held: HeldFloor[] = [];
  for (const target of targets) {
    const packageKey = target.key === '.' ? './package.json' : `${target.key}/package.json`;
    for (const field of updatableFields(target)) {
      for (const [name, spec] of Object.entries(target.packageJson[field] ?? {})) {
        const range = parseFloorRange(spec);
        if (pinned.has(name) || range === undefined) continue;
        const packument = packuments.get(name);
        const hold = (reason: string): void => {
          held.push({ packageKey, field, name, spec, reason });
        };
        if (packument === undefined) {
          hold('registry.npmjs.org does not know this name');
          continue;
        }
        const picked = pickBefore(packument, range, cutoff);
        if (picked === undefined) {
          hold(`no version in range was published before ${cutoff.toISOString()}`);
          continue;
        }
        if (!isAboveFloor(picked, range)) continue;
        edits.push({
          file: join(target.directory, 'package.json'),
          packageKey,
          field,
          name,
          from: spec,
          to: `${range.operator}${picked}`,
          lockRoot: target.lockRoot,
          isolatedConsumer: target.isolatedConsumer,
        });
      }
    }
  }
  return { edits, held };
}

/** An in-scope floor whose lockfile resolves another version: the package.json does not say what is installed. */
export type FloorLockMismatch = {
  readonly packageKey: string;
  readonly field: DependencyField;
  readonly name: string;
  readonly spec: string;
  readonly locked: string;
};

/**
 * Compares every in-scope floor with the version its lockfile resolves for that package, walking up from the
 * package's directory the way Node resolves `node_modules`. A name the lockfile does not record is skipped.
 */
export function floorLockMismatches(
  manifest: NpmManifest,
  targets: readonly UpdateTarget[],
  readLockfile: (file: string) => Readonly<Record<string, Readonly<Record<string, unknown>>>> | undefined,
): readonly FloorLockMismatch[] {
  const pinned = new Set(Object.keys(manifest.dependencies?.pinned ?? {}));
  const mismatches: FloorLockMismatch[] = [];
  for (const target of targets) {
    const entries = readLockfile(join(target.lockRoot, 'package-lock.json'));
    if (entries === undefined) continue;
    const packageKey = target.key === '.' ? './package.json' : `${target.key}/package.json`;
    for (const field of updatableFields(target)) {
      for (const [name, spec] of Object.entries(target.packageJson[field] ?? {})) {
        const range = parseFloorRange(spec);
        if (pinned.has(name) || range === undefined) continue;
        const locked = lockedVersion(entries, relative(target.lockRoot, target.directory), name);
        if (locked !== undefined && locked !== range.text) mismatches.push({ packageKey, field, name, spec, locked });
      }
    }
  }
  return mismatches;
}

function lockedVersion(
  entries: Readonly<Record<string, Readonly<Record<string, unknown>>>>,
  packagePath: string,
  name: string,
): string | undefined {
  for (let directory = packagePath; ; directory = dirname(directory)) {
    const at = directory === '' || directory === '.' ? '' : `${directory}/`;
    const version = entries[`${at}node_modules/${name}`]?.version;
    if (typeof version === 'string') return version;
    if (at === '') return undefined;
  }
}

function isAboveFloor(version: string, range: FloorRange): boolean {
  const parsed = parseVersion(version);
  return parsed !== undefined && compareVersions(parsed, range.floor) > 0;
}
