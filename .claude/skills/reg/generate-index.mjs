/**
 * Renders one page per declared group, and all.md with every live entry. A
 * retired entry only says what replaced it, so the pages leave it out. The
 * index still lists it.
 */
function renderGroupPages(list, groups) {
  const live = list.filter((entry) => entry.tag !== RETIRED);
  const pages = groups.map((group) => ({
    path: join(groupsDir, pageName(group.name)),
    content: renderPage(
      group.name,
      `${group.description} This page holds the full text of the live ${PLURAL} of the group, from [${INDEX}](../${INDEX}).`,
      live.filter((entry) => entry.group === group.name),
      `No live ${NOUN} is in this group yet.`,
    ),
  }));

  pages.push({
    path: join(groupsDir, ALL_PAGE),
    content: renderPage(
      `All ${PLURAL}`,
      `This page holds the full text of every live ${NOUN} of [${INDEX}](../${INDEX}), sorted by ID.`,
      live,
      `No ${NOUN} is live yet.`,
    ),
  });

  return pages;
}

/**
 * Renders one group page from the live entries it holds, or from emptyText
 * if it holds none.
 */
function renderPage(title, intro, list, emptyText) {
  // The reference definitions of all the entries land on one page, where the
  // first of two equal labels wins.
  const labels = new Map();
  const sections = list.map((entry) =>
    [
      `<a id="${entry.id.toLowerCase()}"></a>`,
      "",
      `## ${entry.id}: ${entry.title} \`[${entry.tag}]\``,
      "",
      `> ${entry.summary}`,
      "",
      ...otherFieldLines(entry).flatMap((line) => [line, ""]),
      pageBody(entry, labels),
    ].join("\n"),
  );

  return [
    PAGE_NOTICE,
    "",
    `# ${title}`,
    "",
    intro,
    "",
    ...(sections.length === 0 ? [emptyText, ""] : sections),
  ]
    .join("\n")
    .replace(/\n*$/, "\n");
}

/**
 * Returns one line per field that is neither the title nor the summary and
 * holds a value, as in "Aliases: generation."
 */
function otherFieldLines(entry) {
  return KIND.fields
    .filter((field) => !field.title && !field.summary)
    .map((field) => [field, entry.fields[field.key]])
    .filter(([field, value]) =>
      field.type === LIST ? value.length > 0 : value !== "",
    )
    .map(([field, value]) => fieldLine(field, value));
}

/**
 * Renders one field for a group page: a command in code font, a list with
 * "lines" as one bullet per item, and any other value as one sentence.
 */
function fieldLine(field, value) {
  if (field.command === true) return `${field.label}: \`${value}\``;
  if (field.lines === true) {
    return [`${field.label}:`, "", ...value.map((item) => `- ${item}`)].join(
      "\n",
    );
  }

  const text = field.type === LIST ? value.join(", ") : value;

  return `${field.label}: ${text}${/[.!?]$/.test(text) ? "" : "."}`;
}

/**
 * Copies the text of an entry onto a group page, under its "##" heading. Code
 * stays as it is. Forms that cannot move safely are errors.
 */
function pageBody(entry, labels) {
  const result = [];
  const fences = createFenceTracker();
  const state = { previous: "blank", inList: false };

  for (const line of entry.body.trim().split("\n")) {
    if (fences.step(line)) {
      result.push(line);
      state.previous = "code";
    } else if (isIndentedCode(line, state)) {
      result.push(line);
      state.previous = "indented code";
    } else {
      checkBodyLine(entry, line, state, labels);
      result.push(rewriteLinks(shiftHeading(line)));
      state.previous = lineKind(line);
    }
  }

  if (fences.open) {
    errors.push(
      `${entry.path}: a code block is never closed. Close it with the same fence that opens it`,
    );
  }

  return result.join("\n").concat("\n");
}

/**
 * Says whether the line is indented code. Indented lines after a list item
 * belong to the list, not to an indented code block. Updates the list state.
 */
function isIndentedCode(line, state) {
  const blank = line.trim() === "";

  if (/^ {0,3}([-*+]|\d+[.)])( |$)/.test(line)) state.inList = true;
  else if (!blank && !/^( {2,}|\t)/.test(line)) state.inList = false;

  return (
    !state.inList &&
    /^( {4}|\t)/.test(line) &&
    (state.previous === "blank" || state.previous === "indented code")
  );
}

/**
 * Returns the kind of a line outside code, for the next line: blank, a
 * paragraph, or another block.
 */
function lineKind(line) {
  if (line.trim() === "") return "blank";
  if (/^ {0,3}(#{1,6}(?= |$)|>|\||[-*+] |\d+[.)] )/.test(line)) return "other";

  return "paragraph";
}

/**
 * Checks one line of text outside code: an underlined heading, an HTML link
 * or image, a heading whose anchor matches an ID, and a link label that
 * another entry on the same page uses.
 */
function checkBodyLine(entry, line, state, labels) {
  if (/^ {0,3}(=+|-+)\s*$/.test(line) && state.previous === "paragraph") {
    errors.push(
      `${entry.path}: the text underlines a heading with "${line.trim()}". Write the heading with "#" instead, or add a blank line before a horizontal rule`,
    );
  }

  if (/<(a|img)\s[^>]*(href|src)\s*=/i.test(withoutCode(line))) {
    errors.push(
      `${entry.path}: the text holds an HTML link or image. Write it in Markdown, as in [text](target) or ![text](target)`,
    );
  }

  const heading = /^ {0,3}#{1,6}(?= |$)/.test(line)
    ? slug(
        shiftHeading(line)
          .replace(/^ {0,3}#{1,6} */, "")
          .replace(/ +#+ *$/, ""),
      )
    : undefined;

  if (heading !== undefined && ID_ANCHOR.test(heading)) {
    errors.push(
      `${entry.path}: the heading "${line.trim()}" gets the anchor #${heading}, which the pages use for an entry. Rename the heading`,
    );
  }

  const label = /^ {0,3}\[(?!\^)([^\]]+)\]:/.exec(line)?.[1].toLowerCase();

  if (label === undefined) return;

  const owner = labels.get(label);

  if (owner !== undefined && owner !== entry.id) {
    errors.push(
      `${entry.path}: the link label [${label}] is also defined in ${owner}, and both land on one group page. Rename one label, or use an inline link`,
    );
  }

  labels.set(label, entry.id);
}

/**
 * Moves an ATX heading down two levels, so that it nests under the "##"
 * heading of its entry. Other lines stay as they are.
 */
function shiftHeading(line) {
  const heading = /^ {0,3}(#{1,6})(?= |$)/.exec(line);

  return heading === null
    ? line
    : line.replace(heading[1], "#".repeat(Math.min(6, heading[1].length + 2)));
}

/**
 * Rewrites the relative destination of each inline link and each reference
 * definition, outside code spans. A footnote, as in [^1]: text, is not a
 * link.
 */
function rewriteLinks(line) {
  const reference = /^( {0,3}\[(?!\^)[^\]]+\]:\s*)(<[^>]*>|\S+)(.*)$/.exec(
    line,
  );

  if (reference !== null)
    return reference[1] + rewriteTarget(reference[2]) + reference[3];

  return codeSpans(line)
    .map((part) =>
      part.code
        ? part.text
        : part.text.replace(
            /\]\(\s*(<[^>]*>|[^\s)]+)(\s+(?:"[^"]*"|'[^']*'))?\s*\)/g,
            (_, target, title = "") => `](${rewriteTarget(target)}${title})`,
          ),
    )
    .join("");
}

/**
 * Rewrites one link destination relative to entries/ for groups/. A link that
 * starts with ../ already works, because groups/ and entries/ sit at the same
 * depth.
 */
function rewriteTarget(target) {
  const angle = target.startsWith("<") && target.endsWith(">");
  const bare = angle ? target.slice(1, -1) : target;

  if (/^(\.\.\/|\/|#|[a-z][a-z0-9+.-]*:)/i.test(bare) || bare === "")
    return target;

  const moved = `../${ENTRIES}/${bare.replace(/^\.\//, "")}`;

  return angle ? `<${moved}>` : moved;
}

/**
 * Returns the page name of a group: the anchor of its heading, as in
 * versions.md.
 */
function pageName(group) {
  return `${slug(group)}.md`;
}

/**
 * Finds the files in groups/ that this run does not generate. A page the
 * script wrote, which starts with its notice, is stale and gets deleted. A
 * page that differs from a generated one only by the case of its name gets
 * renamed, because on a case-insensitive disk the two names are one file. If
 * the right name also exists, the other spelling is stale. Any other file is
 * an error, because the script owns the folder and must not delete what
 * someone wrote by hand.
 */
function findStalePages(generated) {
  const result = { stale: [], renamed: [] };

  if (!existsSync(groupsDir)) return result;

  const stat = lstatSync(groupsDir);

  if (stat.isSymbolicLink() || !stat.isDirectory()) {
    errors.push(
      `${groupsDir}: must be a folder, not a file or a link. The script writes the group pages there`,
    );
    return result;
  }

  const byLowerName = new Map(
    generated.map((path) => [path.toLowerCase(), path]),
  );
  const items = readdirSync(groupsDir, { withFileTypes: true });
  const present = new Set(items.map((item) => join(groupsDir, item.name)));

  for (const item of items) {
    const path = join(groupsDir, item.name);

    if (item.name.startsWith(".") || generated.includes(path)) continue;

    const right = byLowerName.get(path.toLowerCase());

    if (
      !item.isFile() ||
      !item.name.endsWith(".md") ||
      !readFileSync(path, "utf8").startsWith(PAGE_NOTICE)
    ) {
      errors.push(
        `${path}: the script owns the ${GROUPS}/ folder and did not write this file. Move it out`,
      );
    } else if (right !== undefined && !present.has(right)) {
      result.renamed.push({ from: path, to: right });
    } else {
      result.stale.push(path);
    }
  }

  return result;
}

