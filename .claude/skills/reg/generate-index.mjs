/**
 * Creates a tracker that follows fenced code blocks as CommonMark does. A
 * fence opens with three or more backticks or tildes, indented by up to three
 * spaces, and closes with the same character, at least as many times. A
 * backtick fence cannot hold a backtick in its info string. step(line) says
 * whether the line is code or a fence line, and open says whether a block is
 * still open.
 */
function createFenceTracker() {
  let fence;

  return {
    get open() {
      return fence !== undefined;
    },
    step(line) {
      if (fence !== undefined) {
        const close = /^ {0,3}(`{3,}|~{3,})\s*$/.exec(line);

        if (
          close !== null &&
          close[1][0] === fence[0] &&
          close[1].length >= fence.length
        )
          fence = undefined;

        return true;
      }

      const open = /^ {0,3}(?:(`{3,})(?!.*`)|(~{3,}))/.exec(line);

      if (open === null) return false;

      fence = open[1] ?? open[2];
      return true;
    },
  };
}

/**
 * Splits a line into inline code spans and the text between them. A code
 * span opens with a run of backticks and closes with a run of the same
 * length. A run with no closing run is plain text.
 */
function codeSpans(line) {
  const parts = [];
  let text = "";
  let i = 0;

  while (i < line.length) {
    if (line[i] !== "`") {
      text += line[i];
      i += 1;
      continue;
    }

    const run = /^`+/.exec(line.slice(i))[0];
    const close = new RegExp(`(?<!\`)${run}(?!\`)`).exec(
      line.slice(i + run.length),
    );

    if (close === null) {
      text += run;
      i += run.length;
      continue;
    }

    const end = i + run.length + close.index + run.length;

    parts.push({ code: false, text }, { code: true, text: line.slice(i, end) });
    text = "";
    i = end;
  }

  parts.push({ code: false, text });

  return parts;
}

/**
 * Returns the line without its inline code spans.
 */
function withoutCode(line) {
  return codeSpans(line)
    .filter((part) => !part.code)
    .map((part) => part.text)
    .join("");
}

