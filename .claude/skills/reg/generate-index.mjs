/**
 * Renders an entry file with its front matter in canonical form and its text
 * unchanged. A list has one "  - item" line per item, not [a, b]: a Markdown
 * link checker reads [a, b] as a link reference and warns. An empty list is
 * "[]", and an empty optional list is left out.
 */
function renderEntryFile(entry) {
  const lines = ["---", `id: ${entry.id}`, `tag: ${entry.tag}`];

  if (entry.group !== "") lines.push(`group: ${scalar(entry.group)}`);

  for (const field of KIND.fields) {
    const value = entry.fields[field.key];

    if (field.type === LIST) {
      if (value.length > 0) {
        lines.push(
          `${field.key}:`,
          ...value.map((item) => `  - ${scalar(item)}`),
        );
      } else if (!field.optional) {
        lines.push(`${field.key}: []`);
      }
    } else if (value !== "") {
      lines.push(`${field.key}: ${scalar(value)}`);
    }
  }

  lines.push("---");

  return `${lines.join("\n")}\n${entry.body}`;
}

/**
 * Renders README.md with a new generated part between the markers.
 */
function renderIndexFile(indexFile, list) {
  const note =
    KIND.note !== undefined && Object.hasOwn(TAGS, KIND.note.tag)
      ? [KIND.note.text, ""]
      : [];
  const block = [
    BEGIN,
    "",
    `The IDs in this file start with \`${PREFIX}${LETTER}-\`.`,
    "",
    table(
      [KIND.tagLabel ?? DEFAULT_TAG_LABEL, "Meaning"],
      Object.entries(TAGS).map(([tag, meaning]) => [`\`[${tag}]\``, meaning]),
    ),
    "",
    ...note,
    `To read the full text of every live ${NOUN} on one page, open [${GROUPS}/${ALL_PAGE}](${GROUPS}/${ALL_PAGE}).`,
    "",
    ...indexTables(list, indexFile.groups),
    END,
  ].join("\n");

  return (
    indexFile.text.slice(0, indexFile.begin) +
    block +
    indexFile.text.slice(indexFile.end + END.length)
  );
}

/**
 * Renders the tables of the index. Without declared groups, the index is one
 * table with no heading. With groups, it starts with the list of groups, then
 * the entries with no group, then one table per group in declared order.
 */
function indexTables(list, groups) {
  if (groups.length === 0) return [indexTable(list), ""];

  const ungrouped = list.filter((entry) => entry.group === "");
  const lines = [
    "## Groups",
    "",
    table(
      ["Group", "Description", capitalize(PLURAL), "Full text"],
      groups.map((group) => [
        `[${group.name}](#${slug(group.name)})`,
        group.description,
        String(list.filter((entry) => entry.group === group.name).length),
        `[${pageName(group.name)}](${GROUPS}/${pageName(group.name)})`,
      ]),
    ),
    "",
  ];

  if (ungrouped.length > 0)
    lines.push("## No group", "", indexTable(ungrouped), "");

  for (const group of groups) {
    const members = list.filter((entry) => entry.group === group.name);

    lines.push(
      `## ${group.name}`,
      "",
      members.length === 0
        ? `No ${NOUN} is in this group yet.`
        : indexTable(members),
      "",
    );
  }

  return lines;
}

/**
 * Renders one table of the index: the ID with its link and its tag, then one
 * column per field of KIND.json.
 */
function indexTable(list) {
  const fields = KIND.fields.filter((field) => field.index !== false);

  return table(
    ["ID", ...fields.map((field) => field.label)],
    list.map((entry) => [
      `[${entry.id}](${ENTRIES}/${entry.id}.md) \`[${entry.tag}]\``,
      ...fields.map((field) =>
        field.type === LIST
          ? entry.fields[field.key].join(", ")
          : entry.fields[field.key],
      ),
    ]),
  );
}

