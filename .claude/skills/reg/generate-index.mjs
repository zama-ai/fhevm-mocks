/**
 * With --verify-commands: asks the check of each command field of a live
 * entry, without a shell, from the root of the repository, whether it
 * enforces the entry. "<command> --<noun>-id <ID>" must exit with code 0 for
 * the ID of the entry, with another code for IDs of the same shape that no
 * entry has, and with another code for at least one of ten live entries
 * that other checks enforce, so a command that accepts anything, or
 * anything that exists, proves nothing. Every answer must print nothing.
 * Only this flag ever runs a command.
 */
function checkCommands(entries) {
  const commandFields = KIND.fields.filter((field) => field.command === true);
  const cwd = realpathSync(REPOSITORY_ROOT);
  const unknownIds = pickUnknownIds(entries);
  const live = entries.filter((entry) => entry.tag !== RETIRED);

  for (const entry of live) {
    for (const field of commandFields) {
      const command = entry.fields[field.key];

      if (command === "") continue;

      const otherIds = pickOtherIds(live, field.key, command);

      checkCommand(entry, command, cwd, unknownIds, otherIds);
    }
  }
}

/**
 * Returns the words of a command field up to its first option: the check
 * itself, without the options it runs with.
 */
function commandKey(command) {
  const words = command.trim().split(WORDS);
  const firstOption = words.findIndex((word) => word.startsWith("-"));

  return (firstOption === -1 ? words : words.slice(0, firstOption)).join(" ");
}

/**
 * Returns up to ten IDs of live entries, in random order, whose command
 * field names another check. The check is asked them one at a time until it
 * says no. A check may enforce some of them too, in part, so it may say yes
 * to a few; one that says yes to all ten says yes to anything that exists.
 * The answer is the same on every run for a check that partly enforces
 * fewer than ten entries of other checks.
 */
function pickOtherIds(live, key, command) {
  const own = commandKey(command);
  const pool = live
    .filter((other) => {
      const value = other.fields[key];

      return value !== undefined && value !== "" && commandKey(value) !== own;
    })
    .map((other) => other.id);
  const picked = [];

  while (picked.length < OTHER_ID_QUESTIONS && pool.length > 0) {
    picked.push(pool.splice(randomInt(pool.length), 1)[0]);
  }

  return picked;
}

/**
 * Returns IDs of the form of this folder that no entry has, picked at random
 * for each run, so a check cannot learn which IDs to refuse: a free two-digit
 * number, a free letter suffix on a taken number if the kind allows suffixes,
 * and a number above every entry.
 */
function pickUnknownIds(entries) {
  const taken = new Set(entries.map((entry) => entry.id));
  const pad = (n) => String(n).padStart(2, "0");
  const id = (number, suffix = "") =>
    `${PREFIX}${LETTER}-${pad(number)}${suffix}`;
  const pick = (candidates) =>
    candidates[randomInt(candidates.length)];
  const numbers = Array.from({ length: 99 }, (_, i) => i + 1);
  const unknown = [];

  const freeNumbers = numbers.filter((number) => !taken.has(id(number)));
  if (freeNumbers.length > 0) unknown.push(id(pick(freeNumbers)));

  if (KIND.suffixes) {
    const takenNumbers = numbers.filter((number) => taken.has(id(number)));
    const freeSuffixed = takenNumbers.flatMap((number) =>
      [..."abcdefghijklmnopqrstuvwxyz"]
        .map((letter) => id(number, letter))
        .filter((candidate) => !taken.has(candidate)),
    );
    if (freeSuffixed.length > 0) unknown.push(pick(freeSuffixed));
  }

  const highest = Math.max(
    0,
    ...entries.map((entry) => entry.number).filter(Number.isFinite),
  );
  unknown.push(id(highest + 1 + randomInt(900)));

  return unknown;
}

/**
 * Asks one check about the entry, then about each unknown ID, and records an
 * error unless the first answer is yes, code 0, every other answer is no,
 * another code, and no answer prints anything.
 */
function checkCommand(entry, command, cwd, unknownIds, otherIds) {
  const words = command.trim().split(WORDS);
  const [program, ...args] = words;
  const checkWord = INTERPRETERS.includes(program) ? args[0] : program;

  if (checkWord === undefined || !isRepositoryFile(checkWord, cwd)) {
    errors.push(
      `${entry.path}: "${command}" does not start with the check. Start with the path of a file of the repository, with a slash, or with ${INTERPRETERS.join(", ")} and that path, as in "node scripts/rule-checks.mjs" or "./check.sh"`,
    );
    return;
  }

  const idArg = `--${NOUN}-id`;
  const own = askCheck(entry, program, [...args, idArg, entry.id], cwd);

  if (own === undefined) return;
  if (own !== 0) {
    errors.push(
      `${entry.path}: "${command} ${idArg} ${entry.id}" exited with code ${own}, not 0, so it does not prove that the check enforces this ${NOUN}`,
    );
    return;
  }

  for (const unknownId of unknownIds) {
    const unknown = askCheck(entry, program, [...args, idArg, unknownId], cwd);

    if (unknown === undefined) return;
    if (unknown === 0) {
      errors.push(
        `${entry.path}: "${command} ${idArg} ${unknownId}" exited with code 0 for an ID that no ${NOUN} has, so its answer for ${entry.id} proves nothing`,
      );
      return;
    }
  }

  if (otherIds.length === 0) return;

  for (const otherId of otherIds) {
    const other = askCheck(entry, program, [...args, idArg, otherId], cwd);

    if (other === undefined || other !== 0) return;
  }

  errors.push(
    `${entry.path}: "${command} ${idArg} <ID>" exited with code 0 for ${otherIds.join(", ")}, which other checks enforce, so its answer for ${entry.id} proves nothing`,
  );
}

/**
 * Runs one question to a check, in a process group of its own, and returns
 * its exit code. Records an error and returns undefined when the check
 * cannot start, times out, prints too much, prints anything at all, or is
 * stopped by a signal: an answer prints nothing, so a check that prints is
 * running more than the answer.
 */
function askCheck(entry, program, args, cwd) {
  const shown = [program, ...args].join(" ");
  const run = spawnSync(program, args, {
    cwd,
    encoding: "utf8",
    timeout: COMMAND_TIMEOUT_MS,
    maxBuffer: COMMAND_MAX_OUTPUT,
    killSignal: COMMAND_KILL_SIGNAL,
    detached: true,
  });

  stopProcessGroup(run.pid);

  if (run.error?.code === "ETIMEDOUT") {
    errors.push(
      `${entry.path}: "${shown}" timed out after ${COMMAND_TIMEOUT_MS / 1000} s`,
    );
  } else if (run.error?.code === "ENOBUFS") {
    errors.push(
      `${entry.path}: "${shown}" printed more than ${COMMAND_MAX_OUTPUT / 1024 / 1024} MB`,
    );
  } else if (run.error !== undefined) {
    errors.push(
      `${entry.path}: "${shown}" could not start: ${run.error.message}`,
    );
  } else if (run.signal !== null) {
    errors.push(`${entry.path}: "${shown}" was stopped by ${run.signal}`);
  } else if (`${run.stdout}${run.stderr}` !== "") {
    errors.push(
      `${entry.path}: "${shown}" printed something, but an answer prints nothing: the check runs more than the answer`,
    );
  } else {
    return run.status;
  }

  return undefined;
}

/**
 * Says whether a word of a command is a path, with a slash, to a file inside
 * the repository. Links are followed, so a link cannot lead outside, and the
 * name must match the file in letter case, as it would on Linux.
 */
function isRepositoryFile(word, root) {
  if (!word.includes("/")) return false;

  const path = resolve(root, word);

  if (!existsSync(path) || !hasExactCase(root, path)) return false;

  const real = realpathSync(path);

  return real.startsWith(root + sep) && statSync(real).isFile();
}

/**
 * Says whether each part of a path below the root matches a name in its
 * folder exactly, letter case included. A case-insensitive disk would find
 * the file anyway.
 */
function hasExactCase(root, path) {
  if (path !== root && !path.startsWith(root + sep)) return false;

  let folder = root;

  for (const part of path.slice(root.length + 1).split(sep)) {
    if (!readdirSync(folder).includes(part)) return false;
    folder = join(folder, part);
  }

  return true;
}

/**
 * Stops every process that a check left behind. The check runs in a process
 * group of its own, so one signal reaches the processes it started.
 */
function stopProcessGroup(pid) {
  // A command that could not start reports pid 0, and process.kill(-0) would
  // stop the group of this script, its shell, and its CI job.
  if (!(pid > 0)) return;

  try {
    process.kill(-pid, COMMAND_KILL_SIGNAL);
  } catch {
    // The group is already gone.
  }
}

/**
 * Checks that IDs start at 01 and leave no gap, because an entry is retired,
 * never deleted. With suffixes, each suffixed ID follows its base ID, as in
 * FR-07, FR-07a, FR-07b.
 */
function checkIds(list) {
  const pad = (n) => String(n).padStart(2, "0");
  let number = 0;
  let suffix = "";

  for (const entry of list) {
    let expected;

    if (entry.suffix === "") {
      number += 1;
      suffix = "";
      expected = `${PREFIX}${LETTER}-${pad(number)}`;
    } else if (entry.number !== number) {
      errors.push(
        `${entry.path}: ${entry.id} needs ${PREFIX}${LETTER}-${pad(entry.number)}, because a suffixed ID follows its base ID`,
      );
      return;
    } else {
      suffix =
        suffix === "" ? "a" : String.fromCharCode(suffix.charCodeAt(0) + 1);
      expected = `${PREFIX}${LETTER}-${pad(number)}${suffix}`;
    }

    if (entry.id !== expected) {
      errors.push(
        `${entry.path}: expected the ID ${expected}. IDs start at 01 and leave no gap, because a ${NOUN} is retired, never deleted`,
      );
      return;
    }
  }
}

/**
 * Checks that each value of a term field, such as a name or an alias, belongs
 * to one live entry. A retired entry frees its values, so the entry that
 * replaces it can take them.
 */
function checkTerms(list) {
  if (TERM_FIELDS.length === 0) return;

  const owners = new Map();
  const termNames = TERM_FIELDS.map((field) => field.key).join(" and ");

  for (const entry of list.filter((entry) => entry.tag !== RETIRED)) {
    const seen = new Set();
    const terms = TERM_FIELDS.flatMap((field) =>
      field.type === LIST ? entry.fields[field.key] : [entry.fields[field.key]],
    ).filter((term) => term !== "");

    for (const term of terms) {
      const key = term.toLowerCase();

      if (seen.has(key)) {
        errors.push(
          `${entry.path}: "${term}" appears twice in its ${termNames}`,
        );
      } else if (owners.has(key)) {
        errors.push(
          `${entry.path}: "${term}" already belongs to ${owners.get(key)}. A term belongs to one ${NOUN}`,
        );
      } else {
        owners.set(key, entry.id);
      }

      seen.add(key);
    }
  }
}

/**
 * Checks the form of each retired entry: empty term lists, a summary that
 * says what replaced it, a live replacement, and a text that only repeats the
 * summary.
 */
function checkRetired(list) {
  const byId = new Map(list.map((entry) => [entry.id, entry]));

  for (const entry of list.filter((entry) => entry.tag === RETIRED)) {
    for (const field of TERM_FIELDS.filter((field) => field.type === LIST)) {
      if (entry.fields[field.key].length > 0) {
        errors.push(
          `${entry.path}: a retired ${NOUN} must have an empty "${field.key}". Move its values to the ${NOUN} that replaces it, or delete them`,
        );
      }
    }

    const match = RETIRED_SUMMARY.exec(entry.summary);

    if (match === null) {
      errors.push(
        `${entry.path}: the "${SUMMARY.key}" of a retired ${NOUN} must be "Merged into <ID>." or "No longer used."`,
      );
      continue;
    }

    checkReplacement(entry, match[1], byId);

    const lines = entry.body.split("\n").filter((line) => line.trim() !== "");
    const titles = lines.filter((line) => /^#{1,6} /.test(line));
    const text = lines.filter((line) => !/^#{1,6} /.test(line)).join("\n");

    if (titles.length > 1 || text !== `> ${entry.summary}`) {
      errors.push(
        `${entry.path}: the text of a retired ${NOUN} is the line "> ${entry.summary}" and nothing else, apart from an optional title`,
      );
    }
  }
}

/**
 * Checks the entry that a retired entry merges into. An entry of another
 * registry cannot be checked here, so the skill lists it as a check by hand.
 */
function checkReplacement(entry, targetId, byId) {
  if (targetId === undefined) return;

  const target = byId.get(targetId);
  const sameFolder = ID_PATTERN.exec(targetId)?.[1] === PREFIX;

  if (targetId === entry.id) {
    errors.push(`${entry.path}: a ${NOUN} cannot be merged into itself`);
  } else if (sameFolder && target === undefined) {
    errors.push(
      `${entry.path}: it is merged into ${targetId}, which does not exist`,
    );
  } else if (target?.tag === RETIRED) {
    errors.push(
      `${entry.path}: it is merged into ${targetId}, which is retired too. Merge it into a live ${NOUN}`,
    );
  }
}

/**
 * Checks that each entry uses only a group that README.md declares, spelled
 * the same way.
 */
function checkGroups(list, groups) {
  const declared = new Set(groups.map((group) => group.name));
  const names =
    groups.length === 0 ? "none" : groups.map((group) => group.name).join(", ");

  for (const entry of list) {
    if (entry.group !== "" && !declared.has(entry.group)) {
      errors.push(
        `${entry.path}: the group "${entry.group}" is not declared in the front matter of ${INDEX}. Declared groups: ${names}`,
      );
    }
  }
}

/**
 * Checks the entries against an index: an indexed ID with no file is a
 * deleted entry, and an ID indexed as retired that is no longer retired is a
 * reused one.
 */
function checkHistory(list, indexed, source) {
  const byId = new Map(list.map((entry) => [entry.id, entry]));

  for (const [id, tag] of indexed) {
    const entry = byId.get(id);

    if (entry === undefined) {
      errors.push(
        `${source}: lists ${id}, but ${ENTRIES}/${id}.md is missing. Never delete a ${NOUN}. Restore the file and retire the ${NOUN}`,
      );
    } else if (tag === RETIRED && entry.tag !== RETIRED) {
      errors.push(
        `${entry.path}: ${source} lists ${id} as retired. A retired ${NOUN} stays retired. To use it again, add a new ${NOUN}`,
      );
    }
  }
}

/**
 * Reads the IDs and tags that README.md indexed at a git ref. A README.md
 * that did not exist at that ref, or that had neither marker yet, as before a
 * conversion, indexed nothing. A broken pair of markers is an error.
 */
function readBaseIndex(ref) {
  let text;

  try {
    text = execFileSync("git", ["-C", folder, "show", `${ref}:./${INDEX}`], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
  } catch (error) {
    const message = String(error.stderr ?? error.message);

    if (!/does not exist|exists on disk, but not in/.test(message)) {
      errors.push(
        `${folder}: cannot read ${INDEX} at ${ref}: ${message.trim()}`,
      );
    }

    return new Map();
  }

  const normalized = text.replace(BYTE_ORDER_MARK, "").replace(CRLF, "\n");
  // A README.md with neither marker had no generated index yet, as before a
  // conversion. A broken pair of markers is an error, as on this branch.
  if (!normalized.includes(BEGIN) && !normalized.includes(END)) {
    return new Map();
  }

  const markers = findMarkers(`${indexPath} at ${ref}`, normalized, true);

  return markers === undefined
    ? new Map()
    : indexedEntries(normalized.slice(markers.begin, markers.end));
}

/**
 * Checks that no two headings of README.md, hand-written or generated, get
 * the same anchor, so that a group link lands on its own heading.
 */
function checkAnchors(path, text) {
  const seen = new Map();
  const fences = createFenceTracker();

  for (const line of text.split("\n")) {
    const heading = fences.step(line)
      ? null
      : /^ {0,3}#{1,6} +(.+?)(?: +#+)? *$/.exec(line);

    if (heading === null) continue;

    const anchor = slug(heading[1]);

    if (anchor === "") {
      errors.push(
        `${path}: the heading "${heading[1]}" gets an empty anchor. Use letters or digits in it`,
      );
    } else if (seen.has(anchor)) {
      errors.push(
        `${path}: the headings "${seen.get(anchor)}" and "${heading[1]}" get the same anchor, #${anchor}. Rename the group or the heading`,
      );
    } else {
      seen.set(anchor, heading[1]);
    }
  }
}

