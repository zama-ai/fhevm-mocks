#!/usr/bin/env node
// Builds the index and the group pages of a registry folder from the front
// matter of its entry files.
//
// Usage: node generate-index.mjs [--check] [--base <git ref>]
//                                [--verify-commands] <folder>
//
// A registry folder holds one kind of entry, such as definitions or rules:
//   README.md   the index: front matter and intro by hand, and a generated
//               part between two markers
//   entries/    one file per entry, named <ID>.md, with its data in its
//               front matter
//   groups/     generated: one page per group, and all.md, with the full
//               text of the live entries
//
// The front matter of README.md names the kind and the prefix, and declares
// the optional groups. The kind, such as definitions, names the sibling skill
// folder reg-<kind>, such as ../reg-definitions/, which holds KIND.json and
// TAGS.json.
//
// With --base, the script also reads README.md at that git ref. Every ID
// indexed there must still have a file, and every ID retired there must stay
// retired.
//
// With --verify-commands, the script asks the check of each command field of
// a live entry, without a shell, from the root of the repository:
// "<command> --<noun>-id <ID>", as in --rule-id, must exit with code 0 for
// the ID of the entry and with another code for an ID that no entry has.
// Only this flag runs anything.
//
// The script checks everything before it writes anything. It never changes
// the text of an entry, the front matter of README.md, or the text outside
// the markers, except that it converts CRLF line endings to LF and removes a
// byte order mark in every file it writes.
//
// Exit codes: 0 when every file is up to date or written, 1 when a rule
// breaks or, with --check, a file is out of date, and 2 for a wrong command
// line or broken settings of the kind.

