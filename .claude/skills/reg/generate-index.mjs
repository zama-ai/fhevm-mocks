/**
 * Returns the anchor that GitHub gives a heading: lower case, without
 * punctuation, with a hyphen for each space.
 */
function slug(heading) {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}\p{Pc} -]/gu, "")
    .replace(/ /g, "-");
}

/**
 * Returns the text with its first letter in capital.
 */
function capitalize(text) {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/**
 * Renders a Markdown table with aligned columns, escaping each "|" in a cell.
 */
function table(header, rows) {
  const cells = [header, ...rows].map((row) =>
    row.map((cell) => cell.replaceAll("|", "\\|")),
  );
  const widths = header.map((_, column) =>
    Math.max(3, ...cells.map((row) => row[column].length)),
  );
  const line = (row) =>
    `| ${row.map((cell, column) => cell.padEnd(widths[column])).join(" | ")} |`;
  const rule = `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`;

  return [line(cells[0]), rule, ...cells.slice(1).map(line)].join("\n");
}

/**
 * Says whether YAML reads the value as plain text: it starts with a letter, a
 * digit, or an opening parenthesis, holds no colon (YAML 1.1 reads 1:30 as a
 * number) and no " #", and is not a keyword, a number, or a date.
 */
function isPlainText(value) {
  return (
    /^[A-Za-z0-9(]/.test(value) &&
    !/:| #|[\t\n]|\s$/.test(value) &&
    !/^(?:true|false|yes|no|on|off|y|n|null)$/i.test(value) &&
    !/^[-+]?[\d._]+(?:[eE][-+]?\d+)?$/.test(value) &&
    !/^[-+]?0[xob][\da-f_]+$/i.test(value) &&
    !/^\d{4}-\d{2}-\d{2}/.test(value)
  );
}

/**
 * Writes a front matter value plain if YAML reads it as text, and quoted
 * otherwise, as Prettier quotes it with the workspace's singleQuote setting:
 * in single quotes, unless the value holds a backslash, or more single quotes
 * than double quotes, then in double quotes. Prettier formats these files on
 * save, so the script writes what Prettier would, and neither undoes the
 * other.
 */
function scalar(value) {
  if (isPlainText(value)) return value;

  const singles = value.split("'").length - 1;
  const doubles = value.split('"').length - 1;

  return value.includes("\\") || singles > doubles
    ? JSON.stringify(value)
    : `'${value.replaceAll("'", "''")}'`;
}
