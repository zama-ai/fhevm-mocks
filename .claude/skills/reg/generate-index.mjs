/**
 * Reads and checks everything, renders everything, then writes the files, or
 * with --check reports the files that are out of date. Only main() and
 * stop(), which only main() calls, set the exit code. Writes nothing if a
 * rule breaks.
 */
function main() {
  if (!parseArgs(process.argv.slice(2))) {
    console.error(USAGE);
    process.exitCode = EXIT_SETUP;
    return;
  }

  // The index names the kind, so the script reads it before the settings.
  const indexFile = readIndexFile(indexPath);

  if (indexFile === undefined) return stop(EXIT_FAILED);
  if (!loadKind(indexFile)) return stop(EXIT_SETUP);

  const entries = readEntries();

  checkEntries(entries, indexFile);

  const { outputs, stalePages, renamedPages } = renderAll(entries, indexFile);

  if (errors.length > 0) return stop(EXIT_FAILED);

  const changed = outputs.filter(
    ({ path, content }) =>
      !existsSync(path) || readFileSync(path, "utf8") !== content,
  );

  process.exitCode = check
    ? reportCheck(changed, stalePages, renamedPages)
    : writeOutputs(changed, stalePages, renamedPages);
}

/**
 * Prints every error once, says that nothing was written, and sets the exit
 * code.
 */
function stop(code) {
  for (const error of new Set(errors)) console.error(`error: ${error}`);
  console.error("Nothing was written.");
  process.exitCode = code;
}

/**
 * Reads --check, --base <git ref>, --verify-commands, and the registry
 * folder from the arguments. Returns false if the command line is wrong.
 */
function parseArgs(args) {
  const folders = [];

  for (let i = 0; i < args.length; i += 1) {
    if (args[i] === "--check") {
      check = true;
    } else if (args[i] === "--verify-commands") {
      verifyCommands = true;
    } else if (
      args[i] === "--base" &&
      args[i + 1] !== undefined &&
      !args[i + 1].startsWith("--")
    ) {
      base = args[i + 1];
      i += 1;
    } else if (args[i].startsWith("--")) {
      return false;
    } else {
      folders.push(args[i]);
    }
  }

  if (folders.length !== 1) return false;

  folder = folders[0];
  indexPath = join(folder, INDEX);
  entriesDir = join(folder, ENTRIES);
  groupsDir = join(folder, GROUPS);

  return true;
}

/**
 * Loads KIND.json and TAGS.json of the kind that README.md names, and builds
 * the patterns that depend on them. Returns false if the settings are broken.
 */
function loadKind(indexFile) {
  const kind = readKindSettings(indexFile.kind);
  const tags = readTagSettings(indexFile.kind);

  if (kind === undefined || tags === undefined) return false;

  if (kind.note !== undefined && !Object.hasOwn(tags, kind.note.tag)) {
    errors.push(
      `${KIND_FILE} of the kind "${indexFile.kind}": the note names the tag "${kind.note.tag}", which ${TAGS_FILE} does not hold`,
    );
    return false;
  }

  const conditionProblems = checkConditionSettings(kind, tags);

  if (conditionProblems.length > 0) {
    for (const problem of conditionProblems) {
      errors.push(`${KIND_FILE} of the kind "${indexFile.kind}" ${problem}`);
    }
    return false;
  }

  KIND = kind;
  TAGS = tags;
  NOUN = KIND.noun;
  PLURAL = KIND.plural;
  LETTER = KIND.letter;
  PREFIX = indexFile.prefix;
  TITLE = KIND.fields.find((field) => field.title);
  SUMMARY = KIND.fields.find((field) => field.summary);
  TERM_FIELDS = KIND.fields.filter((field) => field.term);
  ENTRY_FIELDS = [...RESERVED_FIELDS, ...KIND.fields.map((field) => field.key)];

  const suffix = KIND.suffixes ? "([a-z]?)" : "()";
  const idInText = `[A-Z]*${LETTER}-\\d{2,}${KIND.suffixes ? "[a-z]?" : ""}`;

  ID_PATTERN = new RegExp(`^([A-Z]*)${LETTER}-(\\d{2,})${suffix}$`);
  RETIRED_SUMMARY = new RegExp(
    `^(?:Merged into (${idInText})\\.|No longer used\\.)$`,
  );
  // A tag written in brackets, as the index shows it, from TAGS.json.
  TAG_IN_TEXT = new RegExp(`\\[(?:${Object.keys(TAGS).join("|")})\\]`);
  // The anchor of an entry on a group page, as in d-02, ad-14, or fr-07a.
  ID_ANCHOR = new RegExp(`^[a-z]*${LETTER.toLowerCase()}-\\d{2,}[a-z]?$`);

  return true;
}

/**
 * Runs every check across the entries, and with --base against the index on
 * the base branch.
 */
function checkEntries(entries, indexFile) {
  // A file that fails to parse would show up as a gap in the IDs, so the
  // checks across files wait for it.
  if (errors.length > 0) return;

  checkIds(entries);
  checkTerms(entries);
  checkRetired(entries);
  checkGroups(entries, indexFile.groups);
  checkHistory(entries, indexFile.indexed, indexPath);

  if (base !== undefined) {
    checkHistory(entries, readBaseIndex(base), `${indexPath} at ${base}`);
  }

  if (verifyCommands && errors.length === 0) checkCommands(entries);
}

/**
 * Renders every file the run would write, and finds the pages of groups/ to
 * delete or rename.
 */
function renderAll(entries, indexFile) {
  const outputs = entries.map((entry) => ({
    path: entry.path,
    content: renderEntryFile(entry),
  }));

  if (errors.length > 0) return { outputs, stalePages: [], renamedPages: [] };

  const content = renderIndexFile(indexFile, entries);

  checkAnchors(indexPath, content);
  outputs.push({ path: indexPath, content });

  const pages = renderGroupPages(entries, indexFile.groups);
  const { stale, renamed } = findStalePages(pages.map((page) => page.path));

  outputs.push(...pages);

  return { outputs, stalePages: stale, renamedPages: renamed };
}

/**
 * With --check: lists every file out of date, and returns the exit code.
 */
function reportCheck(changed, stalePages, renamedPages) {
  for (const { path } of changed) console.error(`out of date: ${path}`);
  for (const path of stalePages) {
    console.error(`not generated any more: ${path}`);
  }
  for (const { from, to } of renamedPages) {
    console.error(`wrong case: ${from}, expected ${to}`);
  }

  if (changed.length + stalePages.length + renamedPages.length === 0) {
    return EXIT_OK;
  }

  console.error(
    "Run generate-index.mjs without --check to update these files.",
  );

  return EXIT_FAILED;
}

/**
 * Renames, writes, and deletes the files of the run, and returns the exit
 * code. A rename comes first, so that on a case-insensitive disk a page keeps
 * its content under its right name.
 */
function writeOutputs(changed, stalePages, renamedPages) {
  mkdirSync(groupsDir, { recursive: true });

  for (const { from, to } of renamedPages) {
    renameSync(from, to);
    console.log(`renamed: ${from} to ${to}`);
  }

  for (const { path, content } of changed) {
    writeFileSync(path, content);
    console.log(`updated: ${path}`);
  }

  for (const path of stalePages) {
    rmSync(path);
    console.log(`deleted: ${path}`);
  }

  return EXIT_OK;
}

