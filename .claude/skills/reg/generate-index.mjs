/**
 * Reads one JSON settings file of a kind, from the sibling skill folder
 * reg-<kind>. Records an error and returns undefined if the file is missing,
 * is not valid JSON, or names a key twice.
 */
function readJson(name, kind) {
  const url = new URL(`../${KIND_FOLDER_PREFIX}${kind}/${name}`, import.meta.url);
  let text;

  try {
    text = readFileSync(url, "utf8").replace(BYTE_ORDER_MARK, "");
  } catch (error) {
    errors.push(`cannot read ${name} of the kind "${kind}": ${error.message}`);
    return undefined;
  }

  const duplicate = findDuplicateKey(text);

  if (duplicate !== undefined) {
    errors.push(
      `${name} of the kind "${kind}" names the key "${duplicate}" twice`,
    );
    return undefined;
  }

  try {
    return JSON.parse(text);
  } catch (error) {
    errors.push(
      `${name} of the kind "${kind}" is not valid JSON: ${error.message}`,
    );
    return undefined;
  }
}

/**
 * Returns the first key that one JSON object names twice, or undefined.
 * JSON.parse keeps the last value without a word, so the script looks itself.
 */
function findDuplicateKey(text) {
  const objects = [];
  let expectKey = false;

  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];

    if (char === "{") {
      objects.push(new Set());
      expectKey = true;
    } else if (char === "[") {
      objects.push(undefined);
    } else if (char === "}" || char === "]") {
      objects.pop();
    } else if (char === ",") {
      expectKey = objects.at(-1) !== undefined;
    } else if (char === '"') {
      const end = endOfString(text, i);
      const keys = objects.at(-1);

      if (expectKey && keys !== undefined) {
        const key = text.slice(i + 1, end);

        if (keys.has(key)) return key;
        keys.add(key);
        expectKey = false;
      }

      i = end;
    }
  }

  return undefined;
}

/**
 * Returns the index of the quote that closes the JSON string opening at
 * start.
 */
function endOfString(text, start) {
  let i = start + 1;

  while (i < text.length && text[i] !== '"') i += text[i] === "\\" ? 2 : 1;

  return i;
}

/**
 * Reads and checks KIND.json: the letter, the nouns, the suffixes, the label
 * of the tag column, the fields, and the optional note. Returns undefined and
 * records the errors if anything is wrong.
 */
function readKindSettings(kind) {
  const settings = readJson(KIND_FILE, kind);

  if (settings === undefined) return undefined;

  const problems = checkKindSettings(settings);

  if (problems.length === 0) {
    const letterOwner = findLetterOwner(kind, settings.letter);

    if (letterOwner !== undefined) {
      problems.push(
        `uses the letter "${settings.letter}", which the kind "${letterOwner}" uses too`,
      );
    }
  }

  for (const problem of problems) {
    errors.push(`${KIND_FILE} of the kind "${kind}" ${problem}`);
  }

  return problems.length === 0 ? settings : undefined;
}

/**
 * Returns the problems of the top-level keys of KIND.json, then of each
 * field.
 */
function checkKindSettings(settings) {
  if (!isObject(settings)) return ["is not an object"];

  const problems = unknownKeys(settings, KIND_KEYS);

  if (typeof settings.letter !== "string" || !/^[A-Z]$/.test(settings.letter)) {
    problems.push('needs "letter", one capital letter, as in "D"');
  }

  for (const key of ["noun", "plural"]) {
    if (!isText(settings[key])) {
      problems.push(`needs "${key}", as in "definition" or "definitions"`);
    }
  }

  if (settings.tagLabel !== undefined && !isText(settings.tagLabel)) {
    problems.push('gives "tagLabel" a value that is not text');
  }

  if (
    settings.suffixes !== undefined &&
    typeof settings.suffixes !== "boolean"
  ) {
    problems.push('gives "suffixes" a value other than true or false');
  }

  if (
    settings.note !== undefined &&
    (!isObject(settings.note) ||
      unknownKeys(settings.note, NOTE_KEYS).length > 0 ||
      !isText(settings.note.tag) ||
      !isText(settings.note.text))
  ) {
    problems.push('needs a "note" with a "tag" and a "text", both text');
  }

  if (!Array.isArray(settings.fields) || settings.fields.length === 0) {
    problems.push('needs "fields", a list');
    return problems;
  }

  return [...problems, ...checkFieldSettings(settings.fields)];
}

/**
 * Returns the problems of the fields of KIND.json: each field, its flags,
 * duplicate keys, and the one title field and one summary field.
 */
function checkFieldSettings(fields) {
  const problems = [];
  const keys = new Set();

  for (const field of fields) {
    if (!isObject(field)) {
      problems.push(
        `has a field that is not an object: ${JSON.stringify(field)}`,
      );
    } else {
      problems.push(...checkOneField(field, keys));
      keys.add(field.key);
    }
  }

  const fieldsOk = fields.every(isObject);
  const titles = fieldsOk ? fields.filter((field) => field.title) : [];
  const summaries = fieldsOk ? fields.filter((field) => field.summary) : [];

  if (
    fieldsOk &&
    (titles.length !== 1 || titles[0].type !== TEXT || titles[0].optional)
  ) {
    problems.push(
      'needs exactly one required field of type text with "title": true',
    );
  }

  if (
    fieldsOk &&
    (summaries.length !== 1 ||
      summaries[0].type !== SENTENCE ||
      summaries[0].optional)
  ) {
    problems.push(
      'needs exactly one required field of type sentence with "summary": true',
    );
  }

  return problems;
}

/**
 * Returns the problems of one field of KIND.json: its keys, its key name, a
 * key already used, its type, its label, and its flags.
 */
function checkOneField(field, keys) {
  const name = field.key;
  const problems = unknownKeys(field, FIELD_KEYS, `the field "${name}"`);

  if (!isText(name) || !KEY_NAME.test(name) || RESERVED_FIELDS.includes(name)) {
    problems.push(
      `has a field with a missing or reserved key: ${JSON.stringify(field)}`,
    );
  } else if (keys.has(name)) {
    problems.push(`has the field "${name}" twice`);
  }

  if (!FIELD_TYPES.includes(field.type)) {
    problems.push(
      `gives the field "${name}" a type other than ${FIELD_TYPES.join(", ")}`,
    );
  }

  if (!isText(field.label))
    problems.push(
      `gives the field "${name}" no label, or a label with a space at its start or its end`,
    );

  problems.push(...checkFieldExtras(field));

  for (const flag of FIELD_FLAGS) {
    if (field[flag] !== undefined && typeof field[flag] !== "boolean") {
      problems.push(
        `gives "${flag}" of the field "${name}" a value other than true or false`,
      );
    }
  }

  return problems;
}

/**
 * Returns the problems of the settings that only some fields take: the values
 * of a choice field, the command flag, and the form of the conditions.
 */
function checkFieldExtras(field) {
  const name = field.key;
  const problems = [];

  if (field.type === CHOICE) {
    const values = field.values;

    if (
      !Array.isArray(values) ||
      values.length === 0 ||
      !values.every(isText) ||
      new Set(values).size !== values.length
    ) {
      problems.push(
        `gives the choice field "${name}" no "values", a list of different texts`,
      );
    }
  } else if (field.values !== undefined) {
    problems.push(
      `gives "values" to the field "${name}", which is not a choice`,
    );
  }

  if (
    field.index === false &&
    (field.title === true || field.summary === true)
  ) {
    problems.push(
      `keeps the field "${name}" out of the index, but the index needs its title and its summary`,
    );
  }

  if (field.lines === true && field.type !== LIST) {
    problems.push(`marks the field "${name}" as lines, but it is not a list`);
  }

  if (field.command === true && field.type !== TEXT) {
    problems.push(`marks the field "${name}" as a command, but it is not text`);
  }

  problems.push(...checkConditionForms(field));

  if (field.term === true && field.type === CHOICE) {
    problems.push(
      `marks the choice field "${name}" as a term, but many entries share a choice`,
    );
  }

  return problems;
}

/**
 * Returns the problems of the form of the conditions of one field: each one
 * maps a key to a list of values, or to "not" and a list, and makes sense
 * only on an optional field.
 */
function checkConditionForms(field) {
  const name = field.key;
  const problems = [];

  for (const condition of CONDITIONS) {
    const value = field[condition];

    if (value === undefined) continue;

    if (
      !isObject(value) ||
      Object.keys(value).length === 0 ||
      !Object.values(value).every(isConditionValues)
    ) {
      problems.push(
        `gives "${condition}" of the field "${name}" a form other than { "<field or tag>": ["<value>", …] } or { "<field or tag>": { "not": ["<value>", …] } }`,
      );
    }

    if (field.optional !== true) {
      problems.push(
        `gives "${condition}" to the field "${name}", which must then be optional`,
      );
    }
  }

  return problems;
}

/**
 * Returns the problems of the conditions of KIND.json once the tags are
 * known: each condition names the tag or a choice field, and only values
 * that the tag list or the choice field holds.
 */
function checkConditionSettings(kind, tags) {
  const problems = [];
  const choices = new Map(
    kind.fields
      .filter((field) => field.type === CHOICE)
      .map((field) => [field.key, field.values]),
  );

  for (const field of kind.fields) {
    for (const condition of CONDITIONS) {
      for (const [key, spec] of Object.entries(field[condition] ?? {})) {
        const { values } = conditionValues(spec);
        const allowed =
          key === TAG_FIELD ? Object.keys(tags) : choices.get(key);

        if (allowed === undefined) {
          problems.push(
            `gives "${condition}" of the field "${field.key}" the key "${key}", which is neither the tag nor a choice field`,
          );
        } else {
          problems.push(
            ...checkConditionList(field.key, condition, key, spec, allowed),
          );
        }
      }
    }
  }

  return problems;
}

/**
 * Returns the problems of the values of one condition key: a value the key
 * does not allow, a value listed twice, and a "not" list that names every
 * value, which no entry could ever meet.
 */
function checkConditionList(fieldKey, condition, key, spec, allowed) {
  const { negated, values } = conditionValues(spec);
  const where = `"${condition}" of the field "${fieldKey}"`;
  const problems = values
    .filter((value) => !allowed.includes(value))
    .map(
      (value) =>
        `gives ${where} the value "${value}", which "${key}" does not allow`,
    );

  if (new Set(values).size !== values.length) {
    problems.push(`gives ${where} a value twice`);
  }

  const meeting = allowed.filter((value) => values.includes(value) !== negated);

  if (meeting.length === 0) {
    problems.push(`gives ${where} no value that an entry could meet`);
  } else if (meeting.length === allowed.length) {
    problems.push(
      `gives ${where} every value of "${key}", so it always holds. Remove the condition${condition === "requiredWhen" ? ", and make the field required" : ""}`,
    );
  } else if (
    condition === "requiredWhen" &&
    key === TAG_FIELD &&
    meeting.every((value) => value === RETIRED)
  ) {
    problems.push(
      `gives ${where} only ${RETIRED}, but a retired entry needs no field, so the condition never applies`,
    );
  }

  return problems;
}

/**
 * Says whether a condition value is a list of texts, or an object with only
 * "not" and a list of texts.
 */
function isConditionValues(spec) {
  const list = isObject(spec) ? spec[NOT] : spec;

  return (
    (Array.isArray(spec) ||
      (isObject(spec) && Object.keys(spec).length === 1)) &&
    Array.isArray(list) &&
    list.length > 0 &&
    list.every(isText)
  );
}

/**
 * Returns the values of a condition and whether "not" negates them.
 */
function conditionValues(spec) {
  return Array.isArray(spec)
    ? { negated: false, values: spec }
    : { negated: true, values: spec[NOT] };
}

/**
 * Returns the name of another kind, in a sibling reg-<kind> skill folder, that
 * uses the same letter, or undefined. Two kinds with one letter would produce
 * the same IDs.
 */
function findLetterOwner(kind, letter) {
  const skills = fileURLToPath(new URL("../", import.meta.url));

  for (const folder of readdirSync(skills, { withFileTypes: true })) {
    if (!folder.isDirectory() || !folder.name.startsWith(KIND_FOLDER_PREFIX)) {
      continue;
    }

    const other = folder.name.slice(KIND_FOLDER_PREFIX.length);

    if (other === kind) continue;

    const path = join(skills, folder.name, KIND_FILE);

    if (!existsSync(path)) continue;

    try {
      const text = readFileSync(path, "utf8").replace(BYTE_ORDER_MARK, "");

      if (JSON.parse(text).letter === letter) return other;
    } catch {
      // A broken KIND.json of another kind is that kind's problem.
    }
  }

  return undefined;
}

/**
 * Reads and checks TAGS.json: each tag in capital letters, with a meaning on
 * one line, and RETIRED among them. Returns undefined and records the errors
 * if anything is wrong.
 */
function readTagSettings(kind) {
  const tags = readJson(TAGS_FILE, kind);

  if (tags === undefined) return undefined;

  const problems = [];

  if (!isObject(tags)) {
    problems.push("is not an object");
  } else {
    for (const [tag, meaning] of Object.entries(tags)) {
      if (!/^[A-Z]+$/.test(tag)) {
        problems.push(
          `holds the tag "${tag}", which is not in capital letters only`,
        );
      }
      if (!isText(meaning) || /\n/.test(meaning)) {
        problems.push(`gives "${tag}" a meaning that is not one line of text`);
      }
    }

    if (!Object.hasOwn(tags, RETIRED))
      problems.push(`does not hold ${RETIRED}`);
  }

  for (const problem of problems) {
    errors.push(`${TAGS_FILE} of the kind "${kind}" ${problem}`);
  }

  return problems.length === 0 ? tags : undefined;
}

/**
 * Returns one problem for each key of value outside the allowed keys, such as
 * a misspelled key.
 */
function unknownKeys(value, allowed, where = "") {
  return Object.keys(value)
    .filter((key) => !allowed.includes(key))
    .map(
      (key) =>
        `${where ? `gives ${where} ` : "has "}the unknown key "${key}". Allowed: ${allowed.join(", ")}`,
    );
}

/**
 * Says whether value is a plain object, not null and not a list.
 */
function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

/**
 * Says whether value is text that holds more than spaces.
 */
function isText(value) {
  return (
    typeof value === "string" && value.trim() !== "" && value === value.trim()
  );
}

