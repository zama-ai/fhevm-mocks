/**
 * Reads a text file, without a byte order mark and with LF line endings.
 */
function readText(path) {
  return readFileSync(path, "utf8")
    .replace(BYTE_ORDER_MARK, "")
    .replace(CRLF, "\n");
}

/**
 * Reads every entry file in entries/ and returns the entries sorted by ID.
 */
function readEntries() {
  if (!existsSync(entriesDir)) {
    errors.push(
      `${entriesDir}: the folder does not exist. Create it next to ${INDEX}, with the first entry`,
    );
    return [];
  }

  const result = [];

  for (const item of readdirSync(entriesDir, { withFileTypes: true })) {
    if (item.name.startsWith(".")) continue;

    const path = join(entriesDir, item.name);

    if (!item.isFile() || !item.name.endsWith(".md")) {
      errors.push(
        `${path}: the ${ENTRIES}/ folder holds only ${NOUN} files, named <ID>.md`,
      );
      continue;
    }

    const entry = parseEntryFile(path);

    if (entry === undefined) continue;

    if (`${entry.id}.md` !== item.name) {
      errors.push(
        `${path}: the file name must be ${entry.id}.md, the ID in its front matter`,
      );
    }

    result.push(entry);
  }

  return result.sort(
    (a, b) => a.number - b.number || a.suffix.localeCompare(b.suffix),
  );
}

/**
 * Parses one entry file into its ID, tag, group, fields, and text, and checks
 * the values that one file can show.
 */
function parseEntryFile(path) {
  const text = readText(path);
  const match = FRONT_MATTER.exec(text);

  if (match === null) {
    errors.push(
      `${path}: the file must start with front matter, between a --- line and a second --- line`,
    );
    return undefined;
  }

  const raw = readEntryFrontMatter(path, match[1]);

  if (raw === undefined) return undefined;

  const values = parseEntryValues(path, raw);

  if (values === undefined) return undefined;

  const body = text.slice(match[0].length);
  const idMatch = ID_PATTERN.exec(values.id);

  checkEntryValues(path, values, idMatch, body);

  return {
    path,
    ...values,
    number: idMatch === null ? NaN : Number(idMatch[2]),
    suffix: idMatch?.[3] ?? "",
    title: values.fields[TITLE.key],
    summary: values.fields[SUMMARY.key],
    body,
  };
}

/**
 * Splits the front matter of an entry into its raw values, by field. A field
 * with no value on its line takes the "  - item" lines below it as a list of
 * raw items. Returns undefined if a line is unknown, a field appears twice, or
 * a required field is missing.
 */
function readEntryFrontMatter(path, frontMatter) {
  const raw = {};
  let ok = true;
  let listKey;

  for (const line of frontMatter.split("\n")) {
    const item = LIST_ITEM.exec(line);

    if (item !== null && listKey !== undefined) {
      raw[listKey].push(item[1].trim());
      continue;
    }

    listKey = undefined;

    const colon = line.indexOf(":");
    const key = colon === -1 ? "" : line.slice(0, colon);

    if (!ENTRY_FIELDS.includes(key)) {
      errors.push(
        `${path}: the front matter line "${line}" is not one of the fields ${ENTRY_FIELDS.join(", ")}`,
      );
      ok = false;
    } else if (raw[key] !== undefined) {
      errors.push(`${path}: the field "${key}" appears twice`);
      ok = false;
    } else {
      const value = line.slice(colon + 1).trim();

      if (value === "") {
        raw[key] = [];
        listKey = key;
      } else {
        raw[key] = value;
      }
    }
  }

  const required = [
    "id",
    "tag",
    ...KIND.fields.filter((field) => !field.optional).map((field) => field.key),
  ];

  for (const key of required.filter((key) => raw[key] === undefined)) {
    errors.push(`${path}: the front matter has no "${key}" field`);
    ok = false;
  }

  return ok ? raw : undefined;
}

/**
 * Parses the raw values of an entry into text and lists. Returns undefined if
 * a value cannot be read.
 */
function parseEntryValues(path, raw) {
  const fields = {};

  for (const field of KIND.fields) {
    const value = raw[field.key];

    if (value === undefined) fields[field.key] = field.type === LIST ? [] : "";
    else if (field.type === LIST)
      fields[field.key] = parseList(path, field.key, value);
    else fields[field.key] = parseSingle(path, field.key, value);
  }

  const id = parseSingle(path, "id", raw.id);
  const tag = parseSingle(path, "tag", raw.tag);
  const group =
    raw.group === undefined ? "" : parseSingle(path, "group", raw.group);

  if ([id, tag, group, ...Object.values(fields)].includes(undefined))
    return undefined;

  return { id, tag, group, fields };
}

/**
 * Checks the ID, the tag, the sentence fields, and the text of one entry.
 */
function checkEntryValues(path, values, idMatch, body) {
  if (idMatch === null) {
    const suffix = KIND.suffixes
      ? `, with an optional letter suffix, as in ${PREFIX}${LETTER}-01a`
      : "";

    errors.push(
      `${path}: the ID "${values.id}" must have the form ${PREFIX}${LETTER}-<NN>, as in ${PREFIX}${LETTER}-01${suffix}`,
    );
  } else if (idMatch[1] !== PREFIX) {
    errors.push(
      `${path}: the ID "${values.id}" must start with "${PREFIX}${LETTER}-", from the prefix that ${INDEX} declares`,
    );
  }

  if (!Object.hasOwn(TAGS, values.tag)) {
    errors.push(
      `${path}: the tag "${values.tag}" must be one of ${Object.keys(TAGS).join(", ")}, without brackets`,
    );
  }

  for (const field of KIND.fields.filter((field) => field.type === SENTENCE)) {
    const value = values.fields[field.key];

    if (value === "") continue;
    if (!value.endsWith("."))
      errors.push(`${path}: the field "${field.key}" must end with a period`);
    if (SENTENCE_BREAK.test(value)) {
      errors.push(
        `${path}: the field "${field.key}" must be one sentence. A period followed by a space ends a sentence, so write abbreviations such as "e.g." out in full`,
      );
    }
  }

  checkFieldRules(path, values);

  if (repeatsTag(body)) {
    errors.push(
      `${path}: the text repeats a tag. The tag lives in the front matter only. To quote a tag of another kind, put it in backticks, as in \`[STALE]\``,
    );
  }
}

/**
 * Checks the choice fields of one entry against their values, and each field
 * with a condition against the tag and the other fields.
 */
function checkFieldRules(path, values) {
  const valueOf = (key) =>
    key === TAG_FIELD ? values.tag : values.fields[key];
  const holds = (condition) =>
    Object.entries(condition).every(([key, spec]) => {
      const { negated, values: list } = conditionValues(spec);

      return list.includes(valueOf(key)) !== negated;
    });
  const describe = (condition) =>
    Object.entries(condition)
      .map(([key, spec]) => {
        const { negated, values: list } = conditionValues(spec);

        return `${key} is ${negated ? "not " : ""}${list.join(" or ")}`;
      })
      .join(" and ");
  // A retired entry keeps its fields as they were, so it needs no new field.
  const retired = values.tag === RETIRED;

  for (const field of KIND.fields) {
    const value = values.fields[field.key];
    const present = field.type === LIST ? value.length > 0 : value !== "";

    if (field.type === CHOICE && present && !field.values.includes(value)) {
      errors.push(
        `${path}: the field "${field.key}" must be one of ${field.values.join(", ")}`,
      );
    }

    if (field.command === true && present && SHELL_CHARACTERS.test(value)) {
      errors.push(
        `${path}: the command field "${field.key}" holds a quote or a shell character. Write plain words that reach the check, as in "node scripts/rule-checks.mjs check no-hardcoded-address"`,
      );
    }

    if (present && field.allowedWhen && !holds(field.allowedWhen)) {
      errors.push(
        `${path}: the field "${field.key}" is allowed only when ${describe(field.allowedWhen)}`,
      );
    }

    if (
      !retired &&
      !present &&
      field.requiredWhen &&
      holds(field.requiredWhen)
    ) {
      errors.push(
        `${path}: the field "${field.key}" is required when ${describe(field.requiredWhen)}`,
      );
    }
  }
}

/**
 * Says whether the text holds a tag in brackets outside code. Code may quote
 * a tag, for example a tag of another kind that shares its name.
 */
function repeatsTag(body) {
  const fences = createFenceTracker();

  return body
    .split("\n")
    .some((line) => !fences.step(line) && TAG_IN_TEXT.test(withoutCode(line)));
}

/**
 * Parses the raw value of a field that holds one value. Records an error and
 * returns undefined if the field holds a list of items instead.
 */
function parseSingle(path, field, value) {
  if (!Array.isArray(value)) return parseScalar(path, field, value);
  if (value.length === 0) return parseScalar(path, field, "");

  errors.push(
    `${path}: the field "${field}" holds one value, not a list of items`,
  );
  return undefined;
}

/**
 * Parses one front matter value, plain, single-quoted, or double-quoted.
 * Records an error and returns undefined for a YAML comment, a broken quote,
 * or an empty value.
 */
function parseScalar(path, field, value) {
  const quoted = value.startsWith('"') || value.startsWith("'");

  if (!quoted && / #/.test(value)) {
    errors.push(
      `${path}: the field "${field}" holds " #", which YAML reads as the start of a comment. Put the value in quotes, or remove the comment`,
    );
    return undefined;
  }

  const parsed = value.startsWith('"')
    ? parseQuoted(path, field, value)
    : value.startsWith("'")
      ? parseSingleQuoted(path, field, value)
      : value;

  if (parsed === undefined) return undefined;

  if (parsed.trim() === "") {
    errors.push(`${path}: the field "${field}" is empty`);
    return undefined;
  }

  if (parsed !== parsed.trim()) {
    errors.push(
      `${path}: the field "${field}" starts or ends with a space. Remove it`,
    );
    return undefined;
  }

  return parsed;
}

/**
 * Parses a double-quoted value with the rules of JSON. Records an error and
 * returns undefined if the quotes do not close it.
 */
function parseQuoted(path, field, value) {
  try {
    const parsed = JSON.parse(value);

    if (typeof parsed === "string") return parsed;
  } catch {
    // The error below says what to fix.
  }

  errors.push(
    `${path}: the field "${field}" is not a valid double-quoted value: ${value}. Escape a quote inside it as \\"`,
  );
  return undefined;
}

/**
 * Parses a single-quoted value with the rules of YAML: no escape, and '' for
 * a quote inside it. Records an error and returns undefined if the quotes do
 * not close it.
 */
function parseSingleQuoted(path, field, value) {
  const match = /^'((?:[^']|'')*)'$/.exec(value);

  if (match !== null) return match[1].replaceAll("''", "'");

  errors.push(
    `${path}: the field "${field}" is not a valid single-quoted value: ${value}. Write a quote inside it as ''`,
  );
  return undefined;
}

/**
 * Parses a front matter list into its items: either the "  - item" lines that
 * readEntryFrontMatter collected, or a flow list such as [a, "b, c"], honoring
 * double quotes. The script writes every list back as "  - item" lines.
 */
function parseList(path, field, value) {
  if (Array.isArray(value)) {
    if (value.length === 0) {
      errors.push(
        `${path}: the field "${field}" has no items. Write one "  - item" line per item below it, or "${field}: []" for none`,
      );
      return undefined;
    }

    const result = value.map((item) => parseScalar(path, field, item));

    return result.includes(undefined) ? undefined : result;
  }

  if (!value.startsWith("[") || !value.endsWith("]")) {
    errors.push(
      `${path}: the field "${field}" must be a list: one "  - item" line per item below "${field}:", or "${field}: []" for none`,
    );
    return undefined;
  }

  const inner = value.slice(1, -1).trim();

  if (inner === "") return [];

  const items = [];
  let current = "";
  let quoted = false;

  for (let i = 0; i < inner.length; i += 1) {
    const char = inner[i];

    if (char === "\\" && quoted) {
      current += char + (inner[i + 1] ?? "");
      i += 1;
    } else if (char === '"') {
      quoted = !quoted;
      current += char;
    } else if (char === "," && !quoted) {
      items.push(current.trim());
      current = "";
    } else {
      current += char;
    }
  }

  items.push(current.trim());

  const result = items.map((item) => parseScalar(path, field, item));

  return result.includes(undefined) ? undefined : result;
}

