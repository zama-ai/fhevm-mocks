/**
 * Reads README.md: its front matter, which names the kind and the prefix and
 * declares the groups, its two markers, and the IDs it already indexes.
 */
function readIndexFile(path) {
  if (!existsSync(path)) {
    errors.push(
      `${path}: the file does not exist. Create it with the front matter, the title, and the two markers`,
    );
    return undefined;
  }

  const text = readText(path);
  const markers = findMarkers(path, text, true);
  const settings = readIndexFrontMatter(path, text);

  if (markers === undefined || settings === undefined) return undefined;

  const { begin, end } = markers;

  return {
    text,
    begin,
    end,
    indexed: indexedEntries(text.slice(begin, end)),
    ...settings,
  };
}

/**
 * Parses the front matter of README.md: "kind:", "prefix:", and an optional
 * "groups:" block, one group per line, in the order the index shows them.
 * Blank lines are allowed.
 */
function readIndexFrontMatter(path, text) {
  const match = FRONT_MATTER.exec(text);

  if (match === null) {
    errors.push(
      /^\s*\n---\n/.test(text)
        ? `${path}: the front matter must start on the first line, with no blank line before it`
        : `${path}: the file must start with front matter that names the kind and the prefix, as in:\n---\nkind: definitions\nprefix: ""\n---`,
    );
    return undefined;
  }

  const state = { settings: { groups: [] }, seen: new Set(), inGroups: false };
  const count = errors.length;

  for (const line of match[1].split("\n")) readIndexLine(path, line, state);

  const { settings } = state;

  if (!KEY_NAME.test(settings.kind ?? "")) {
    errors.push(
      `${path}: the front matter needs "kind:", the name of a kind such as definitions or rules`,
    );
  }

  if (settings.prefix === undefined || !/^[A-Z]*$/.test(settings.prefix)) {
    errors.push(
      `${path}: the front matter needs "prefix:", capital letters or "" for the empty prefix`,
    );
  }

  return errors.length === count ? settings : undefined;
}

/**
 * Reads one line of the front matter of README.md into the state: a field, a
 * group line, or a blank line.
 */
function readIndexLine(path, line, state) {
  if (line.trim() === "") return;

  if (state.inGroups && line.startsWith("  ")) {
    const group = readGroupLine(path, line, state.settings.groups);

    if (group !== undefined) state.settings.groups.push(group);
    return;
  }

  state.inGroups = false;

  if (/^[a-z]+:[^ ]/.test(line)) {
    errors.push(
      `${path}: the front matter line "${line}" needs a space after the colon, as YAML requires`,
    );
    return;
  }

  const entry = /^([a-z]+):(?: (.*))?$/.exec(line);

  if (entry === null || !INDEX_FIELDS.includes(entry[1])) {
    errors.push(
      `${path}: the front matter line "${line}" is not one of ${INDEX_FIELDS.join(", ")}`,
    );
    return;
  }

  const [, key, rawValue = ""] = entry;
  const value = rawValue.trim();

  if (state.seen.has(key)) {
    errors.push(`${path}: the field "${key}" appears twice`);
    return;
  }

  state.seen.add(key);

  if (key === "groups") {
    if (value !== "")
      errors.push(
        `${path}: "groups:" takes no value on its line. Write one "  <Group>: <description>" line per group below it`,
      );
    state.inGroups = true;
  } else if (value === "") {
    errors.push(
      `${path}: the field "${key}" is empty. Write "" for the empty prefix`,
    );
  } else if (!/^["']/.test(value) && / #/.test(value)) {
    errors.push(
      `${path}: the field "${key}" holds " #", which YAML reads as the start of a comment. Remove the comment`,
    );
  } else {
    // A value may stand in quotes, as "" or '' for the empty prefix must.
    state.settings[key] = /^(["']).*\1$/.test(value) ? value.slice(1, -1) : value;
  }
}

/**
 * Parses and checks one group line of the front matter of README.md: a valid
 * name, a one-sentence description, no duplicate, and no reserved name.
 */
function readGroupLine(path, line, groups) {
  const entry = /^ {2}([^:]*): (.*)$/.exec(line);

  if (entry === null) {
    errors.push(
      `${path}: cannot read the group line "${line}". Write it as "  <Group>: <description>"`,
    );
    return undefined;
  }

  const name = entry[1];
  const raw = entry[2].trim();

  if (!GROUP_NAME.test(name) || !isPlainText(name) || name !== name.trim()) {
    errors.push(
      `${path}: the group name "${name}" must start with a letter or a digit, hold no quote, colon, #, bracket, or other YAML character, and not be a YAML keyword or number such as Yes or 1.0`,
    );
    return undefined;
  }

  if (!/^["']/.test(raw) && !isPlainText(raw)) {
    errors.push(
      `${path}: put the description of the group "${name}" in quotes, because YAML would not read it as plain text`,
    );
    return undefined;
  }

  const description = parseScalar(path, `groups.${name}`, raw);

  if (description === undefined) return undefined;

  if (!description.endsWith(".") || SENTENCE_BREAK.test(description)) {
    errors.push(
      `${path}: the description of the group "${name}" must be one sentence that ends with a period`,
    );
  }

  if (RESERVED_HEADINGS.includes(name.toLowerCase())) {
    errors.push(
      `${path}: "${name}" cannot name a group, because the index uses it as a heading`,
    );
  } else if (pageName(name) === ALL_PAGE) {
    errors.push(
      `${path}: "${name}" cannot name a group, because ${GROUPS}/${ALL_PAGE} holds every entry`,
    );
  } else if (
    groups.some((group) => group.name.toLowerCase() === name.toLowerCase())
  ) {
    errors.push(`${path}: the group "${name}" is declared twice`);
  }

  return { name, description };
}

/**
 * Finds the BEGIN and END markers, each once, alone on its line, outside
 * code. A marker quoted anywhere else would move the index and hide the rows
 * that record past IDs. With report false, as for the base branch, a missing
 * or broken pair is not an error.
 */
function findMarkers(path, text, report) {
  const found = { [BEGIN]: [], [END]: [] };
  const fences = createFenceTracker();
  let offset = 0;

  for (const line of text.split("\n")) {
    const fenced = fences.step(line);

    if (line.includes(BEGIN) || line.includes(END)) {
      const marker = line.includes(BEGIN) ? BEGIN : END;

      if (!fenced && line === marker) found[marker].push(offset);
      else if (report)
        errors.push(
          `${path}: the marker "${marker}" appears inside a line or a code block. Keep each marker alone on its own line, and quote it nowhere else`,
        );
    }

    offset += line.length + 1;
  }

  if (
    found[BEGIN].length !== 1 ||
    found[END].length !== 1 ||
    found[END][0] < found[BEGIN][0]
  ) {
    if (report)
      errors.push(
        `${path}: the file needs each of these two lines exactly once, in this order, where the index goes:\n${BEGIN}\n${END}`,
      );
    return undefined;
  }

  return { begin: found[BEGIN][0], end: found[END][0] };
}

/**
 * Returns the ID and the tag of every row of a generated index.
 */
function indexedEntries(block) {
  return new Map(
    [...block.matchAll(INDEX_ROW)].map((match) => [match[1], match[2]]),
  );
}

