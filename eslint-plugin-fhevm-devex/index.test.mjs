// Run: node --test eslint-plugin-fhevm-devex/index.test.mjs (from the workspace root).
import { describe, it } from 'node:test';

import { RuleTester } from 'eslint';
import tseslint from 'typescript-eslint';

import plugin from './index.mjs';

RuleTester.describe = describe;
RuleTester.it = it;

const ruleTester = new RuleTester({ languageOptions: { parser: tseslint.parser } });
const rule = plugin.rules['no-generation-number'];
const error = (name) => ({ messageId: 'generationNumber', data: { name } });

ruleTester.run('fhevm-devex/no-generation-number', rule, {
  valid: [
    '// The upgrade from <vN-1> to <vN>.',
    // Quoted values (R-05, case 4).
    '// Imports `@fhevm/host-contracts-cleartext-v13-dev`, and the folder `host-contracts-cleartext/v14/pkg`.',
    '/** Calls `updateV13ToV14()`. */',
    // Not generation names.
    '// updateV13ToV14 and v13BootstrapConfig are identifiers; Node v22.23.5; tag v0.14.4; Hardhat v2 and v3.',
    '// extraData v1 and v2.',
    // Not comments.
    "const name = 'v13';",
    'const v14 = 1;',
    // A generated file, whose first comment is the generator's header (R-05, case 1).
    '// AUTO-GENERATED by `fhevm-npm generate cleartext-config` — DO NOT EDIT.\n// The v14 TypeScript face.',
    // An allowed pattern: a past-tense fact about one release (R-05, case 3).
    { code: '// v14 added `fheMulDiv`.', options: [{ allow: [String.raw`v1\d added`] }] },
  ],
  invalid: [
    { code: '// Deploy a fresh v13 stack.', errors: [error('v13')] },
    { code: '/* v14.0 and v13.0 */', errors: [error('v14.0'), error('v13.0')] },
    { code: '/**\n * Upgrades a v13 stack to v14.\n */', errors: [error('v13'), error('v14')] },
    { code: '// The first release from 1.0 on is v1.0.', errors: [error('v1.0')] },
    // A path outside backticks is prose, not a quoted value.
    { code: '// See host-contracts-cleartext/v13/README.md.', errors: [error('v13')] },
    // The allow pattern covers only what it matches.
    { code: '// v14 added it; v13 had none.', options: [{ allow: [String.raw`v1\d added`] }], errors: [error('v13')] },
    // The header must be the FIRST comment: a later "DO NOT EDIT" does not exempt the file.
    { code: '// Deploy on v14.\n// DO NOT EDIT this line.', errors: [error('v14')] },
    // The reported column is the name's own, inside the comment.
    { code: 'const a = 1; // on v14', errors: [{ ...error('v14'), line: 1, column: 20, endColumn: 23 }] },
  ],
});

// A past fact about one release puts its generation name in backticks too (R-05, case 3): the backticked name
// passes, and the rest of the comment is still checked.
ruleTester.run('fhevm-devex/no-generation-number, with a past fact in backticks', rule, {
  valid: [
    '// `v14` added no contract to the host set.',
    "// `v13`'s `v12` -> `v13` update called `initializeFromMigration`.",
    '// `ProtocolConfig`, which `v13` introduced. A fact about `v14.1` and `v1.0` too.',
    '/**\n * Added in `v14`: the anchor.\n */',
  ],
  invalid: [
    // Only the backticked name passes.
    { code: '// `v14` added it, and the v13 stack is live.', errors: [error('v13')] },
    // Brackets are not a marker.
    { code: '// [v14] added it.', errors: [error('v14')] },
    // The message offers the backticks for the very name it reports.
    { code: '// v14 added no contract.', errors: [{ message: /put the name in backticks: `v14`/ }] },
  ],
});
